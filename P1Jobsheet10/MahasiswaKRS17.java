package P1Jobsheet10;

public class MahasiswaKRS17 {
    String nim, nama, prodi;

    public MahasiswaKRS17(String nim, String nama, String prodi) {
        this.nim = nim;
        this.nama = nama;
        this.prodi = prodi;
    }

    public String toString() {
        return "NIM: " + nim + " | Nama: " + nama + " | Prodi: " + prodi;
    }
}
